// supabase/seed/teams.json (source of truth) -> supabase/seed_teams.sql.   node scripts/build-teams-seed.mjs [--check]
// The JSON was built on 2026-11-02 from Wikipedia (read-only MediaWiki API): team lists from each league's season page,
// wiki_page = the club/team page stem such that "<season> <wiki_page> season" (or " team" for NCAA) is the season page title.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../supabase/', import.meta.url))
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

export function buildSql(teams) {
  const rows = teams.map((t) => `  (${q(t.id)}, ${q(t.league_id)}, ${q(t.name)}, ${q(t.short_name)}, ${q(t.wiki_page)}, ${q(t.official_calendar_url)})`)
  return `-- GENERATED by scripts/build-teams-seed.mjs from supabase/seed/teams.json. Do not edit by hand.
-- Idempotent. A club in two competitions (e.g. Arsenal in epl and ucl) has one row per league.
-- wiki_page is the stem of the Wikipedia team-season title (NCAA: "<season> <wiki_page> team"; others: "<season> <wiki_page> season").
-- NBA/NHL rows have wiki_page null and an official_calendar_url (links verified 2026-11-03, supabase/seed/official-calendar-links.json).
insert into fanday.teams (id, league_id, name, short_name, wiki_page, official_calendar_url) values
${rows.join(',\n')}
on conflict (id) do update set league_id = excluded.league_id, name = excluded.name, short_name = excluded.short_name,
  wiki_page = excluded.wiki_page, official_calendar_url = coalesce(excluded.official_calendar_url, fanday.teams.official_calendar_url);
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = buildSql(JSON.parse(readFileSync(root + 'seed/teams.json', 'utf8')))
  if (process.argv.includes('--check')) { if (readFileSync(root + 'seed_teams.sql', 'utf8') !== sql) { console.error('seed_teams.sql is stale: run node scripts/build-teams-seed.mjs'); process.exit(1) } }
  else writeFileSync(root + 'seed_teams.sql', sql)
}
